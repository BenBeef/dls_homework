class ReLU(TensorOp):
    def compute(self, a):
        ### BEGIN YOUR SOLUTION
        return array_api.where(a > 0, 1, 0) * a
        ### END YOUR SOLUTION

    def gradient(self, out_grad, node):
        ### BEGIN YOUR SOLUTION
        tens = Tensor(array_api.where(node.inputs[0].numpy() > 0, 1, 0))
        return multiply(out_grad, tens)
        ### END YOUR SOLUTION


def relu(a):
    return ReLU()(a)
